// Freezes the practice-game card pool (stats of every card in the 5 guide decks + the decklists)
// into js/game/pool-data.js, so games don't change when daily data refreshes.
// Run: node scripts/make-game-pool.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const cards = new Map(JSON.parse(readFileSync(new URL('../data/cards.json', import.meta.url))).map(c => [c.id, c]));
const meta = JSON.parse(readFileSync(new URL('../data/meta.json', import.meta.url)));
const LEADERS = [['ST30-001', 'luffy-ace'], ['OP14-020', 'mihawk'], ['OP13-001', 'luffy'], ['OP13-004', 'sabo'], ['OP09-062', 'robin']];

const pool = {};
const decks = {};
for (const [leaderId, key] of LEADERS) {
  const d = meta.decks.find(x => x.leaderId === leaderId);
  if (!d) throw new Error(`No meta deck for ${leaderId}`);
  const list = d.lists[0];
  decks[key] = { key, name: d.name, leaderId, entries: list.cards.map(c => ({ id: c.id, count: c.count })), source: `${list.place || ''} ${list.event || ''} ${list.date || ''}`.trim() };
  for (const id of [leaderId, ...list.cards.map(c => c.id)]) {
    const c = cards.get(id);
    if (!c) throw new Error(`Missing card ${id}`);
    pool[id] = { id, name: c.name, type: c.type, colors: c.colors, cost: c.cost, power: c.power, counter: c.counter, life: c.life, attribute: c.attribute, traits: c.traits, text: c.text, img: c.img };
  }
}
const out = `// Generated by scripts/make-game-pool.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
export const POOL = ${JSON.stringify(pool, null, 1)};
export const DECKS = ${JSON.stringify(decks, null, 1)};
`;
writeFileSync(new URL('../js/game/pool-data.js', import.meta.url), out);
console.log(`pool: ${Object.keys(pool).length} cards, ${Object.keys(decks).length} decks`);
